export const GLYPH_W = 5
export const GLYPH_H = 7

export interface TextOpts {
  scale?: number
  align?: 'left' | 'center' | 'right'
  /** 1px drop shadow in this colour, drawn under the glyphs. */
  shadow?: string
  /** Extra pixels between glyphs, before scaling. */
  tracking?: number
}

export function textWidth(text: string, opts: TextOpts = {}): number {
  const scale = opts.scale ?? 1
  const tracking = opts.tracking ?? 1
  if (!text.length) return 0
  return (text.length * (GLYPH_W + tracking) - tracking) * scale
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  opts: TextOpts = {},
): void {
  const scale = opts.scale ?? 1
  const tracking = opts.tracking ?? 1
  const upper = text.toUpperCase()
  const w = textWidth(upper, opts)
  let ox = Math.round(x)
  if (opts.align === 'center') ox = Math.round(x - w / 2)
  else if (opts.align === 'right') ox = Math.round(x - w)
  const oy = Math.round(y)

  const stamp = (dx: number, dy: number, col: string) => {
    ctx.fillStyle = col
    let cx = ox + dx
    for (const ch of upper) {
      const g = GLYPHS[ch]
      if (g) {
        for (let ry = 0; ry < GLYPH_H; ry++) {
          const row = g[ry]
          let run = 0
          for (let rx = 0; rx <= GLYPH_W; rx++) {
            const on = rx < GLYPH_W && row[rx] === '#'
            if (on) {
              run++
            } else if (run) {
              ctx.fillRect(cx + (rx - run) * scale, oy + dy + ry * scale, run * scale, scale)
              run = 0
            }
          }
        }
      }
      cx += (GLYPH_W + tracking) * scale
    }
  }

  if (opts.shadow) stamp(scale, scale, opts.shadow)
  stamp(0, 0, color)
}
